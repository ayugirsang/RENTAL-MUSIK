-- jurnal buku besar, dan rekonsiliasi tagihan pada database yang sudah ada.

alter table public.penyewaan
  add column if not exists status_pembayaran_sewa text;
update public.penyewaan
set status_pembayaran_sewa = 'Belum Dicatat'
where status_pembayaran_sewa is null;
alter table public.penyewaan
  alter column status_pembayaran_sewa set default 'Belum Lunas',
  alter column status_pembayaran_sewa set not null;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'penyewaan_status_pembayaran_sewa_check'
      and conrelid = 'public.penyewaan'::regclass
  ) then
    alter table public.penyewaan
      add constraint penyewaan_status_pembayaran_sewa_check
      check (status_pembayaran_sewa in ('Belum Dicatat', 'Belum Lunas', 'Sebagian', 'Lunas'));
  end if;
end;
$$;

alter table public.penyewaan
  add column if not exists basis_pencatatan text;
update public.penyewaan
set basis_pencatatan = 'Kas'
where basis_pencatatan is null;
alter table public.penyewaan
  alter column basis_pencatatan set default 'Akrual',
  alter column basis_pencatatan set not null;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'penyewaan_basis_pencatatan_check'
      and conrelid = 'public.penyewaan'::regclass
  ) then
    alter table public.penyewaan
      add constraint penyewaan_basis_pencatatan_check
      check (basis_pencatatan in ('Kas', 'Akrual'));
  end if;
end;
$$;

create index if not exists idx_penyewaan_status_pembayaran
  on public.penyewaan(status_pembayaran_sewa);

create table if not exists public.pembayaran_sewa (
  id_pembayaran_sewa bigint generated by default as identity primary key,
  id_sewa bigint not null references public.penyewaan(id_sewa) on delete restrict,
  tgl_bayar date not null default current_date,
  jumlah_bayar numeric(14,2) not null check (jumlah_bayar > 0),
  metode_bayar text not null check (metode_bayar in ('Tunai', 'Transfer', 'QRIS')),
  created_at timestamptz not null default now()
);

alter table public.jurnal_akuntansi
  alter column id_pengembalian drop not null,
  add column if not exists id_sewa bigint references public.penyewaan(id_sewa) on delete restrict,
  add column if not exists id_pembayaran_sewa bigint references public.pembayaran_sewa(id_pembayaran_sewa) on delete restrict;

create index if not exists idx_pembayaran_sewa_rental
  on public.pembayaran_sewa(id_sewa);
create index if not exists idx_jurnal_sewa
  on public.jurnal_akuntansi(id_sewa);

grant select, insert, update, delete on table public.pembayaran_sewa to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;
revoke update, delete on table public.pembayaran_sewa from anon, authenticated;

create or replace function public.catat_penyewaan()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.total_biaya > 0 and new.basis_pencatatan = 'Akrual' then
    insert into public.jurnal_akuntansi
      (id_sewa, tgl_jurnal, kode_akun, nama_akun, debit, kredit, keterangan)
    values
      (new.id_sewa, new.tgl_sewa, '1120', 'Piutang Sewa', new.total_biaya, 0,
       'Pengakuan pendapatan sewa #' || new.id_sewa),
      (new.id_sewa, new.tgl_sewa, '4100', 'Pendapatan Sewa Alat Musik', 0, new.total_biaya,
       'Pengakuan pendapatan sewa #' || new.id_sewa);
  end if;
  return new;
end;
$$;

drop trigger if exists trg_catat_penyewaan on public.penyewaan;
create trigger trg_catat_penyewaan
after insert on public.penyewaan
for each row execute function public.catat_penyewaan();

create or replace function public.validasi_pembayaran_sewa()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  v_total numeric(14,2);
  v_terbayar numeric(14,2);
begin
  select total_biaya into v_total
  from public.penyewaan where id_sewa = new.id_sewa
  for update;
  if not found then
    raise exception 'Data penyewaan tidak ditemukan';
  end if;
  select coalesce(sum(jumlah_bayar), 0) into v_terbayar
  from public.pembayaran_sewa where id_sewa = new.id_sewa;
  if new.jumlah_bayar > v_total - v_terbayar then
    raise exception 'Pembayaran melebihi sisa tagihan sewa';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_validasi_pembayaran_sewa on public.pembayaran_sewa;
create trigger trg_validasi_pembayaran_sewa
before insert on public.pembayaran_sewa
for each row execute function public.validasi_pembayaran_sewa();

create or replace function public.catat_pembayaran_sewa()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  v_total numeric(14,2);
  v_terbayar numeric(14,2);
  v_basis text;
  v_kode_akun text;
  v_nama_akun text;
  v_keterangan text;
begin
  select total_biaya, basis_pencatatan into v_total, v_basis
  from public.penyewaan where id_sewa = new.id_sewa;
  select coalesce(sum(jumlah_bayar), 0) into v_terbayar
  from public.pembayaran_sewa where id_sewa = new.id_sewa;

  update public.penyewaan
  set status_pembayaran_sewa = case
    when v_terbayar >= v_total then 'Lunas'
    when v_terbayar > 0 then 'Sebagian'
    else 'Belum Lunas'
  end
  where id_sewa = new.id_sewa;

  if v_basis = 'Akrual' then
    v_kode_akun := '1120';
    v_nama_akun := 'Piutang Sewa';
    v_keterangan := 'Pengurangan piutang sewa #' || new.id_sewa;
  else
    v_kode_akun := '4100';
    v_nama_akun := 'Pendapatan Sewa Alat Musik';
    v_keterangan := 'Penerimaan sewa lama #' || new.id_sewa;
  end if;

  insert into public.jurnal_akuntansi
    (id_sewa, id_pembayaran_sewa, tgl_jurnal, kode_akun, nama_akun, debit, kredit, keterangan)
  values
    (new.id_sewa, new.id_pembayaran_sewa, new.tgl_bayar, '1110', 'Kas', new.jumlah_bayar, 0,
     'Pembayaran sewa #' || new.id_pembayaran_sewa || ' (' || new.metode_bayar || ')'),
    (new.id_sewa, new.id_pembayaran_sewa, new.tgl_bayar, v_kode_akun, v_nama_akun, 0, new.jumlah_bayar,
     v_keterangan);
  return new;
end;
$$;

drop trigger if exists trg_catat_pembayaran_sewa on public.pembayaran_sewa;
create trigger trg_catat_pembayaran_sewa
after insert on public.pembayaran_sewa
for each row execute function public.catat_pembayaran_sewa();

