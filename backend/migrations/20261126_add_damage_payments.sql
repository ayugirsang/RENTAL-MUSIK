-- Add a separate, auditable payment flow for assessed damage receivables.
-- Apply after add_damage_handling.sql and 20261125_admin_auth_and_rls.sql.

create table if not exists public.pembayaran_kerusakan (
  id_pembayaran_kerusakan bigint generated by default as identity primary key,
  id_pengembalian bigint not null references public.pengembalian(id_pengembalian) on delete restrict,
  tgl_bayar date not null default current_date,
  jumlah_bayar numeric(14,2) not null check (jumlah_bayar > 0),
  metode_bayar text not null check (metode_bayar in ('Tunai', 'Transfer', 'QRIS')),
  created_at timestamptz not null default now()
);

create index if not exists idx_pembayaran_kerusakan_pengembalian
  on public.pembayaran_kerusakan(id_pengembalian);

alter table public.pembayaran_kerusakan enable row level security;
revoke all on public.pembayaran_kerusakan from public, anon, authenticated;
grant select, insert on public.pembayaran_kerusakan to authenticated;
grant select, insert, update, delete on public.pembayaran_kerusakan to service_role;
grant usage, select on sequence public.pembayaran_kerusakan_id_pembayaran_kerusakan_seq to authenticated, service_role;

drop policy if exists ritme_admin_read_damage_payments on public.pembayaran_kerusakan;
create policy ritme_admin_read_damage_payments
  on public.pembayaran_kerusakan for select to authenticated
  using ((select public.is_ritme_admin()));

drop policy if exists ritme_admin_insert_damage_payments on public.pembayaran_kerusakan;
create policy ritme_admin_insert_damage_payments
  on public.pembayaran_kerusakan for insert to authenticated
  with check ((select public.is_ritme_admin()));

create or replace function public.validasi_pembayaran_kerusakan()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  v_total numeric(14,2);
  v_terbayar numeric(14,2);
begin
  select biaya_kerusakan into v_total
  from public.pengembalian
  where id_pengembalian = new.id_pengembalian
  for update;

  if not found then
    raise exception 'Data pengembalian tidak ditemukan';
  end if;
  if v_total <= 0 then
    raise exception 'Tidak ada tagihan biaya kerusakan pada pengembalian ini';
  end if;

  select coalesce(sum(jumlah_bayar), 0) into v_terbayar
  from public.pembayaran_kerusakan
  where id_pengembalian = new.id_pengembalian;

  if new.jumlah_bayar > v_total - v_terbayar then
    raise exception 'Pembayaran melebihi sisa biaya kerusakan';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_validasi_pembayaran_kerusakan on public.pembayaran_kerusakan;
create trigger trg_validasi_pembayaran_kerusakan
before insert on public.pembayaran_kerusakan
for each row execute function public.validasi_pembayaran_kerusakan();

create or replace function public.catat_pembayaran_kerusakan()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  insert into public.jurnal_akuntansi
    (id_pengembalian, tgl_jurnal, kode_akun, nama_akun, debit, kredit, keterangan)
  values
    (new.id_pengembalian, new.tgl_bayar, '1110', 'Kas', new.jumlah_bayar, 0,
     'Pembayaran biaya kerusakan #' || new.id_pembayaran_kerusakan || ' (' || new.metode_bayar || ')'),
    (new.id_pengembalian, new.tgl_bayar, '1140', 'Piutang Ganti Rugi Kerusakan', 0, new.jumlah_bayar,
     'Pelunasan piutang kerusakan #' || new.id_pembayaran_kerusakan);
  return new;
end;
$$;

drop trigger if exists trg_catat_pembayaran_kerusakan on public.pembayaran_kerusakan;
create trigger trg_catat_pembayaran_kerusakan
after insert on public.pembayaran_kerusakan
for each row execute function public.catat_pembayaran_kerusakan();
