-- Struktur tabel, relasi, indeks, hak akses dasar, dan RLS demo.
-- Jalankan terlebih dahulu, lalu jalankan triggers.sql dan seed.sql.

create table if not exists public.pelanggan (
  id_pelanggan bigint generated by default as identity primary key,
  nama text not null check (length(trim(nama)) > 0),
  no_hp text not null,
  alamat text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.alat_musik (
  id_alat bigint generated by default as identity primary key,
  nama_alat text not null check (length(trim(nama_alat)) > 0),
  harga_sewa_per_hari numeric(14,2) not null check (harga_sewa_per_hari >= 0),
  denda_per_hari numeric(14,2) not null check (denda_per_hari >= 0),
  status text not null default 'Tersedia' check (status in ('Tersedia', 'Disewa')),
  created_at timestamptz not null default now()
);

create table if not exists public.penyewaan (
  id_sewa bigint generated by default as identity primary key,
  id_pelanggan bigint not null references public.pelanggan(id_pelanggan) on delete restrict,
  tgl_sewa date not null,
  tgl_rencana_kembali date not null,
  total_biaya numeric(14,2) not null default 0 check (total_biaya >= 0),
  status_sewa text not null default 'Berlangsung' check (status_sewa in ('Berlangsung', 'Selesai')),
  status_pembayaran_sewa text not null default 'Belum Lunas'
    check (status_pembayaran_sewa in ('Belum Dicatat', 'Belum Lunas', 'Sebagian', 'Lunas')),
  basis_pencatatan text not null default 'Akrual' check (basis_pencatatan in ('Kas', 'Akrual')),
  created_at timestamptz not null default now(),
  check (tgl_rencana_kembali >= tgl_sewa)
);

create table if not exists public.detail_penyewaan (
  id_detail bigint generated by default as identity primary key,
  id_sewa bigint not null references public.penyewaan(id_sewa) on delete cascade,
  id_alat bigint not null references public.alat_musik(id_alat) on delete restrict,
  jumlah integer not null default 1 check (jumlah > 0),
  subtotal numeric(14,2) not null check (subtotal >= 0),
  unique (id_sewa, id_alat)
);

create table if not exists public.pengembalian (
  id_pengembalian bigint generated by default as identity primary key,
  id_sewa bigint not null unique references public.penyewaan(id_sewa) on delete restrict,
  tgl_kembali_aktual date not null,
  hari_terlambat integer not null default 0 check (hari_terlambat >= 0),
  total_denda numeric(14,2) not null default 0 check (total_denda >= 0),
  status_pembayaran_denda text not null default 'Belum Lunas'
    check (status_pembayaran_denda in ('Belum Lunas', 'Sebagian', 'Lunas')),
  created_at timestamptz not null default now()
);

create table if not exists public.pembayaran_denda (
  id_pembayaran bigint generated by default as identity primary key,
  id_pengembalian bigint not null references public.pengembalian(id_pengembalian) on delete restrict,
  tgl_bayar date not null default current_date,
  jumlah_bayar numeric(14,2) not null check (jumlah_bayar > 0),
  metode_bayar text not null check (metode_bayar in ('Tunai', 'Transfer', 'QRIS')),
  created_at timestamptz not null default now()
);

create table if not exists public.pembayaran_sewa (
  id_pembayaran_sewa bigint generated by default as identity primary key,
  id_sewa bigint not null references public.penyewaan(id_sewa) on delete restrict,
  tgl_bayar date not null default current_date,
  jumlah_bayar numeric(14,2) not null check (jumlah_bayar > 0),
  metode_bayar text not null check (metode_bayar in ('Tunai', 'Transfer', 'QRIS')),
  created_at timestamptz not null default now()
);

create table if not exists public.jurnal_akuntansi (
  id_jurnal bigint generated by default as identity primary key,
  id_pengembalian bigint references public.pengembalian(id_pengembalian) on delete restrict,
  id_sewa bigint references public.penyewaan(id_sewa) on delete restrict,
  id_pembayaran_sewa bigint references public.pembayaran_sewa(id_pembayaran_sewa) on delete restrict,
  tgl_jurnal date not null default current_date,
  kode_akun text not null,
  nama_akun text not null,
  debit numeric(14,2) not null default 0 check (debit >= 0),
  kredit numeric(14,2) not null default 0 check (kredit >= 0),
  keterangan text not null default '',
  created_at timestamptz not null default now(),
  check ((debit > 0 and kredit = 0) or (kredit > 0 and debit = 0))
);

create index if not exists idx_penyewaan_status_tanggal
  on public.penyewaan(status_sewa, tgl_rencana_kembali);
create index if not exists idx_penyewaan_status_pembayaran
  on public.penyewaan(status_pembayaran_sewa);
create index if not exists idx_pengembalian_tanggal
  on public.pengembalian(tgl_kembali_aktual);
create index if not exists idx_jurnal_tanggal
  on public.jurnal_akuntansi(tgl_jurnal desc, id_jurnal desc);
create index if not exists idx_pembayaran_pengembalian
  on public.pembayaran_denda(id_pengembalian);
create index if not exists idx_pembayaran_sewa_rental
  on public.pembayaran_sewa(id_sewa);


grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on table
  public.pelanggan,
  public.alat_musik,
  public.penyewaan,
  public.detail_penyewaan,
  public.pengembalian,
  public.pembayaran_denda,
  public.pembayaran_sewa,
  public.jurnal_akuntansi
to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;
revoke update, delete on table public.pembayaran_sewa from anon, authenticated;


-- Aplikasi tanpa login untuk prototipe akademik. Amankan sebelum penggunaan publik.
do $$
declare
  nama_tabel text;
begin
  foreach nama_tabel in array array[
    'pelanggan', 'alat_musik', 'penyewaan', 'detail_penyewaan',
    'pengembalian', 'pembayaran_denda', 'pembayaran_sewa', 'jurnal_akuntansi'
  ] loop
    execute format('alter table public.%I enable row level security', nama_tabel);
    execute format('drop policy if exists %I on public.%I', 'demo_anon_access_' || nama_tabel, nama_tabel);
    execute format(
      'create policy %I on public.%I for all to anon, authenticated using (true) with check (true)',
      'demo_anon_access_' || nama_tabel, nama_tabel
    );
  end loop;
end;
$$;
